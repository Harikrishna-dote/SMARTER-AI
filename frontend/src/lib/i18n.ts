export const SUPPORTED_LOCALES: Locale[] = [
  'en',
  'te',
  'hi',
  'es',
  'fr',
  'de',
  'zh',
  'ja',
  'ar',
];

export const DEFAULT_LOCALE: Locale = 'en';

export const LOCALE_NAMES: Record<Locale, string> = {
  en: 'English',
  te: 'తెలుగు',
  hi: 'हिंदी',
  es: 'Español',
  fr: 'Français',
  de: 'Deutsch',
  zh: '中文',
  ja: '日本語',
  ar: 'العربية',
};

function getNestedValue(obj: TranslationDict, path: string): string | undefined {
  const keys = path.split('.');
  let current: string | TranslationDict = obj;
  for (const key of keys) {
    if (current && typeof current === 'object' && key in current) {
      current = current[key];
    } else {
      return undefined;
    }
  }
  return typeof current === 'string' ? current : undefined;
}

export function t(key: string, locale: Locale = DEFAULT_LOCALE): string {
  const translation = getNestedValue(translations[locale], key);
  if (translation) {
    return translation;
  }
  const fallback = getNestedValue(translations[DEFAULT_LOCALE], key);
  if (fallback) {
    return fallback;
  }
  return key;
}

export function setLocale(locale: Locale): void {
  if (typeof window !== 'undefined') {
    localStorage.setItem('smarterai.locale', locale);
  }
}

export function getLocale(): Locale {
  if (typeof window !== 'undefined') {
    const stored = localStorage.getItem('smarterai.locale');
    if (stored && SUPPORTED_LOCALES.includes(stored as Locale)) {
      return stored as Locale;
    }
    const browserLang = navigator.language.split('-')[0];
    if (SUPPORTED_LOCALES.includes(browserLang as Locale)) {
      return browserLang as Locale;
    }
  }
  return DEFAULT_LOCALE;
}
